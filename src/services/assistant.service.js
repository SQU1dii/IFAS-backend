async function listConversations(workspaceId, userId) {
  return db()('conversations')
    .where({ workspace_id: workspaceId, user_id: userId })
    .orderBy('updated_at', 'desc')
    .select('id', 'title', 'created_at', 'updated_at');
}

async function getConversation(workspaceId, userId, convId) {
  const conv = await db()('conversations').where({ id: convId, workspace_id: workspaceId, user_id: userId }).first();
  if (!conv) throw notFound('Conversation not found.', 'CONV_NOT_FOUND');
  const messages = await db()('messages').where({ conversation_id: convId }).orderBy('created_at', 'asc')
    .select('id', 'role', 'content', 'created_at');
  return { ...conv, messages };
}

async function deleteConversation(workspaceId, userId, convId) {
  const conv = await db()('conversations').where({ id: convId, workspace_id: workspaceId, user_id: userId }).first();
  if (!conv) throw notFound('Conversation not found.', 'CONV_NOT_FOUND');
  await db()('messages').where({ conversation_id: convId }).del();
  await db()('conversations').where({ id: convId }).del();
  return { deleted: true };
}

async function exportConversation(workspaceId, userId, convId) {
  const conv = await db()('conversations').where({ id: convId, workspace_id: workspaceId, user_id: userId }).first();
  if (!conv) throw notFound('Conversation not found.', 'CONV_NOT_FOUND');
  const messages = await db()('messages').where({ conversation_id: convId }).orderBy('created_at', 'asc')
    .select('role', 'content', 'created_at', 'context_snapshot');

  let markdown = `# ${conv.title}\n\n`;
  markdown += `**Workspace:** ${workspaceId}  \n`;
  markdown += `**Created:** ${new Date(conv.created_at).toLocaleString()}  \n`;
  markdown += `**Updated:** ${new Date(conv.updated_at).toLocaleString()}  \n\n`;

  for (const m of messages) {
    const role = m.role === 'user' ? '👤 You' : '🤖 Assistant';
    markdown += `## ${role}\n${m.content}\n\n`;
  }

  return { filename: `ifas-conversation-${convId}.md`, content: markdown };
}

