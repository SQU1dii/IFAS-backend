async function sendMessage(workspace, userId, membership, userContent, conversationId) {
  if (!userContent || !userContent.trim()) throw badRequest('Message content is required.', null, 'EMPTY_MESSAGE');

  // Get or create conversation
  let convId = conversationId;
  if (!convId) {
    const [id] = await db()('conversations').insert({
      workspace_id: workspace.id,
      user_id:      userId,
      title:        userContent.slice(0, 60) || 'New conversation',
    });
    convId = id;
  } else {
    const existing = await db()('conversations').where({ id: convId, workspace_id: workspace.id, user_id: userId }).first();
    if (!existing) throw notFound('Conversation not found.', 'CONV_NOT_FOUND');
  }

  // Load recent history (last 6 messages for context)
  const history = await db()('messages')
    .where({ conversation_id: convId })
    .orderBy('created_at', 'asc')
    .limit(6)
    .select('role', 'content');

  // Build rich context (all data needed for deterministic answers)
  const context = await buildRichContext(workspace, membership);

  // Classify intent
  const intent = classifyIntent(userContent);

  // Handle out-of-scope / security intents immediately (no LLM)
  if (OUT_OF_SCOPE_INTENTS.has(intent)) {
    const template = TEMPLATES[intent];
    const answer = template(context, userContent) + LIMITATIONS_NOTICE;

    await db()('messages').insert({ conversation_id: convId, role: 'user', content: userContent });
    await db()('messages').insert({
      conversation_id: convId,
      role: 'assistant',
      content: answer,
      context_snapshot: JSON.stringify({ intent, data: extractDataForIntent(intent, context) }),
    });
    await db()('conversations').where({ id: convId }).update({ updated_at: new Date() });

    return {
      conversation_id: convId,
      message: { role: 'assistant', content: answer },
      structured: {
        answer,
        intent,
        data: extractDataForIntent(intent, context),
        charts: suggestCharts(intent, context),
        follow_ups: suggestFollowUps(intent, context),
      },
    };
  }

  // Try deterministic handler first
  const deterministic = await handleIntent(intent, context, userContent);

  if (deterministic) {
    // Deterministic answer — use it, no LLM needed
    const finalAnswer = deterministic.answer + LIMITATIONS_NOTICE;

    await db()('messages').insert({ conversation_id: convId, role: 'user', content: userContent });
    await db()('messages').insert({
      conversation_id: convId,
      role: 'assistant',
      content: finalAnswer,
      context_snapshot: JSON.stringify({ intent, data: deterministic.data }),
    });
    await db()('conversations').where({ id: convId }).update({ updated_at: new Date() });

    return {
      conversation_id: convId,
      message: { role: 'assistant', content: finalAnswer },
      structured: {
        answer: deterministic.answer,
        intent: deterministic.intent,
        data: deterministic.data,
        charts: suggestCharts(deterministic.intent, context),
        follow_ups: suggestFollowUps(deterministic.intent, context),
      },
    };
  }

  // Fallback: GENERAL_ADVICE or unclear → use LLM (mock or live)
  // Build system prompt with context summary
  const systemPrompt = buildSystemPrompt(context);
  const messages = [
    { role: 'system', content: systemPrompt },
    ...history.map(m => ({ role: m.role, content: m.content })),
    { role: 'user', content: userContent },
  ];

  const aiContent = await callAiProvider(messages);
  const finalAnswer = aiContent + LIMITATIONS_NOTICE;

  await db()('messages').insert({ conversation_id: convId, role: 'user', content: userContent });
  await db()('messages').insert({
    conversation_id: convId,
    role: 'assistant',
    content: finalAnswer,
    context_snapshot: JSON.stringify({ intent: 'LLM_FALLBACK', data: {} }),
  });
  await db()('conversations').where({ id: convId }).update({ updated_at: new Date() });

  return {
    conversation_id: convId,
    message: { role: 'assistant', content: finalAnswer },
    structured: {
      answer: aiContent,
      intent: 'LLM_FALLBACK',
      data: {},
      charts: suggestCharts('GENERAL_ADVICE', context),
      follow_ups: suggestFollowUps('GENERAL_ADVICE', context),
    },
  };
}

