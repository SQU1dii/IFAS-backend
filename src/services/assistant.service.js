const INTENT_PATTERNS = [
  // High-confidence factual intents → handled deterministically
  // Ordered by specificity (more specific first)
  { intent: 'BIGGEST_EXPENSE',      patterns: [/\b(biggest|largest|highest|single).*\b(expense|transaction|purchase|spend)\b/i] },
  { intent: 'SAVINGS_GOAL',         patterns: [/\b(saving|goal|target).*\b(laptop|emergency|holiday|fund)\b/i, /\bhow close.*goal\b/i, /\bprogress.*goal\b/i, /\b(savings? goals?|show.*goals?|my goals?)\b/i] },
  { intent: 'ALERT_EXPLANATION',    patterns: [/\b(alert|unusual|anomaly|flagged)\b/i, /\bwhy.*alert\b/i, /\bexplain.*alert\b/i, /\bany.*alerts?\b/i, /\bopen alerts?\b/i] },
  { intent: 'TOP_CATEGORIES',       patterns: [/\b(top|biggest|largest|highest)\b.*\b(category|categories|expense)\b/i, /\bwhere.*(money|spending)\b/i, /\bcategory breakdown\b/i] },
  { intent: 'BUDGET_STATUS',        patterns: [/\b(budget|over budget|under budget|budget.*status|budget.*used|percent.*budget)\b/i, /\bam i on track\b/i, /\bon track.*budget\b/i] },
  { intent: 'MONTHLY_SUMMARY',      patterns: [/\b(spent|spend|expense|expenditure)\b.*\b(last|this|current)\s*month\b/i, /\bhow much.*spend\b/i, /\btotal.*expense\b/i, /\bmonthly (summary|spending|expenses)\b/i, /\bthis month.*(spend|expense)\b/i] },
  { intent: 'INCOME_SUMMARY',       patterns: [/\b(income|revenue|earned)\b.*\b(last|this|current)\s*month\b/i, /\bhow much.*(income|earned)\b/i, /\bmy income\b/i, /\bmonthly income\b/i] },
  { intent: 'NET_POSITION',         patterns: [/\b(net|profit|loss|surplus|deficit)\b.*\b(last|this|current)\s*month\b/i, /\bnet (position|income|profit)\b/i, /\bnet position\b/i] },
  { intent: 'CASH_FLOW',            patterns: [/\b(cash flow|cashflow|inflow|outflow)\b/i] },
  { intent: 'FORECAST',             patterns: [/\b(forecast|predict|project|next|future)\b.*\b(month|quarter|year|spend|expense|cost)\b/i, /\bwill i spend\b/i, /\bnext (month|quarter|year)\b/i] },
  { intent: 'PERIOD_COMPARISON',    patterns: [/\b(compare|comparison|versus|vs\.?)\b.*\b(month|year|period)\b/i, /\b(rose|increase|decrease|went up|went down).*\b(month|year)\b/i, /\bthis year.*last year\b/i, /\bmonth over month\b/i, /\bcompare.*month\b/i] },
  { intent: 'CATEGORY_DETAIL',      patterns: [/\bhow much.*\b(on|spent on|spent.*)\b/i, /\b(spending|spend).*(groceries|transport|rent|dining|entertainment|utilities|clothing|education|health)\b/i, /\b(spent|spending) on\b/i] },

  // Role-restricted / cross-workspace / out-of-scope
  { intent: 'CROSS_WORKSPACE',      patterns: [/\b(other|another|different)\b.*\b(workspace|business|organization|personal)\b/i] },
  { intent: 'OUT_OF_SCOPE_INVESTMENT', patterns: [/\b(invest|shares|stocks|unit trust|mutual fund|treasury bill|crypto|bitcoin)\b/i, /\bshould i (buy|invest)\b/i] },
  { intent: 'OUT_OF_SCOPE_TAX_LEGAL',  patterns: [/\b(tax|legal|lawyer|attorney|compliance|regulatory)\b/i] },
  { intent: 'OUT_OF_SCOPE_CREDIT',      patterns: [/\b(loan|credit|borrow|mortgage|overdraft)\b/i] },

  // Security
  { intent: 'PROMPT_INJECTION',     patterns: [/\b(ignore|forget|disregard|override)\b.*\b(rule|instruction|prompt|system)\b/i, /\bpretend you are\b/i, /\bshow.*(system|prompt|instruction)\b/i] },
  { intent: 'SECRET_REQUEST',       patterns: [/\b(api key|password|secret|token|credential)\b/i] },

  // Unrelated
  { intent: 'UNRELATED',            patterns: [/\b(football|soccer|match|game|weather|movie|celebrity|news|politics|sports)\b/i] },
];

const OUT_OF_SCOPE_INTENTS = new Set([
  'OUT_OF_SCOPE_INVESTMENT',
  'OUT_OF_SCOPE_TAX_LEGAL',
  'OUT_OF_SCOPE_CREDIT',
  'CROSS_WORKSPACE',
  'PROMPT_INJECTION',
  'SECRET_REQUEST',
  'UNRELATED',
]);

function classifyIntent(text) {
  const lower = text.toLowerCase();
  for (const { intent, patterns } of INTENT_PATTERNS) {
    for (const pattern of patterns) {
      if (pattern.test(lower)) return intent;
    }
  }
  return 'GENERAL_ADVICE'; // fallback → LLM or generic template
}

