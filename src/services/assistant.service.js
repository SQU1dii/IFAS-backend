async function buildRichContext(workspace, membership) {
  const wsId   = workspace.id;
  const wsType = workspace.workspace_type;
  const now    = new Date();

  // Find the latest month with data (training data ends Oct 2026)
  const latestTxn = await db()('transactions')
    .where({ workspace_id: wsId, status: 'POSTED' })
    .orderBy('txn_date', 'desc')
    .first('txn_date');
  const latestMonth = latestTxn ? latestTxn.txn_date.toISOString().slice(0, 7) : now.toISOString().slice(0, 7);
  const thisMonthStart = `${latestMonth}-01`;
  const thisMonthEnd = new Date(latestTxn ? new Date(latestTxn.txn_date).getTime() : now.getTime()).toISOString().slice(0, 10);

  // Previous month (relative to latest data month) — use UTC to avoid timezone shifts
  const latestDate = latestTxn ? new Date(latestTxn.txn_date) : now;
  const latestYear = latestDate.getUTCFullYear();
  const latestMonthIdx = latestDate.getUTCMonth(); // 0-11
  const prevMonthIdx = latestMonthIdx === 0 ? 11 : latestMonthIdx - 1;
  const prevYear = latestMonthIdx === 0 ? latestYear - 1 : latestYear;
  const prevMonth = `${prevYear}-${String(prevMonthIdx + 1).padStart(2, '0')}`;
  const prevMonthStart = `${prevMonth}-01`;
  // Last day of previous month in UTC
  const prevMonthEndDate = new Date(Date.UTC(prevYear, prevMonthIdx + 1, 0));
  const prevMonthEnd = prevMonthEndDate.toISOString().slice(0, 10);

  // ── Current month transactions (latest available month) ──
  const [txnsThisMonth, txnsPrevMonth] = await Promise.all([
    db()('transactions')
      .where({ workspace_id: wsId, status: 'POSTED' })
      .whereBetween('txn_date', [thisMonthStart, thisMonthEnd])
      .select('txn_type', 'amount', 'category_id', 'txn_date', 'description'),
    db()('transactions')
      .where({ workspace_id: wsId, status: 'POSTED' })
      .whereBetween('txn_date', [prevMonthStart, prevMonthEnd])
      .select('txn_type', 'amount', 'category_id', 'txn_date', 'description'),
  ]);

  // Aggregate by category (with names)
  const categories = await db()('categories').where({ workspace_id: wsId }).select('id', 'name', 'category_type');
  const catById = new Map(categories.map(c => [c.id, c.name]));
  const catTypeById = new Map(categories.map(c => [c.id, c.category_type]));

  function aggregate(txns) {
    let income = 0, expense = 0;
    const byCat = new Map();
    for (const r of txns) {
      const amt = Number(r.amount);
      if (r.txn_type === 'INCOME') income += amt;
      if (r.txn_type === 'EXPENSE') {
        expense += amt;
        const catName = catById.get(r.category_id) || `Category ${r.category_id}`;
        byCat.set(catName, (byCat.get(catName) || 0) + amt);
      }
    }
    const topCats = Array.from(byCat.entries())
      .sort(([,a],[,b]) => b - a)
      .slice(0, 10)
      .map(([name, total]) => ({ category: name, total: Math.round(total) }));
    return { income: Math.round(income), expense: Math.round(expense), net: Math.round(income - expense), topCategories: topCats };
  }

  const current = aggregate(txnsThisMonth);
  const previous = aggregate(txnsPrevMonth);

  // ── Budgets (current month) ──
  const budgets = await budgetSvc.listBudgets(wsId);
  const currentBudgets = budgets.filter(b => {
    const start = b.period_start.toISOString().slice(0, 7);
    return start === latestMonth;
  });
  const budgetSummaries = await Promise.all(
    currentBudgets.slice(0, 10).map(async (b) => {
      const status = await budgetSvc.getBudgetStatus(wsId, b.id).catch(() => b);
      const catName = b.category_id ? catById.get(b.category_id) : 'Overall';
      const deptName = b.department_id ? (await db()('departments').where({ id: b.department_id }).first('name'))?.name : null;
      return {
        id: b.id,
        category: catName,
        department: deptName,
        limit: Number(b.amount_limit),
        spent: Number(status.spent || 0),
        percent: Number(status.percent_used || 0),
        remaining: Math.max(0, Number(b.amount_limit) - Number(status.spent || 0)),
        over: (status.percent_used || 0) >= 100,
        near: (status.percent_used || 0) >= 80,
      };
    })
  );

  // ── Savings goals ──
  const goals = await db()('savings_goals')
    .where({ workspace_id: wsId })
    .select('id', 'name', 'target_amount', 'saved_amount', 'target_date');
  const goalSummaries = goals.map(g => ({
    id: g.id,
    name: g.name,
    target: Number(g.target_amount),
    saved: Number(g.saved_amount),
    percent: g.target_amount > 0 ? Math.round((Number(g.saved_amount) / Number(g.target_amount)) * 100) : 0,
    remaining: Math.max(0, Number(g.target_amount) - Number(g.saved_amount)),
    target_date: g.target_date,
  }));

  // ── Alerts ──
  const openAlerts = await alertRepo.listOpen(wsId, { limit: 10 });
  const alertSummaries = openAlerts.map(a => ({
    id: a.id,
    type: a.alert_type,
    severity: a.severity,
    reason: a.reason,
    created_at: a.created_at,
  }));

  // ── Transactions count ──
  const txnCountThisMonth = txnsThisMonth.length;
  const txnCountPrevMonth = txnsPrevMonth.length;

  // ── All-time totals (for "this year" questions) ──
  const yearStart = `${latestDate.getFullYear()}-01-01`;
  const txnsThisYear = await db()('transactions')
    .where({ workspace_id: wsId, status: 'POSTED' })
    .where('txn_date', '>=', yearStart)
    .select('txn_type', 'amount', 'category_id');
  const yearAgg = aggregate(txnsThisYear);

  // ── Largest single expense this month ──
  const largestExpense = txnsThisMonth
    .filter(r => r.txn_type === 'EXPENSE')
    .sort((a, b) => Number(b.amount) - Number(a.amount))[0];

  return {
    workspace_type: wsType,
    currency: 'KES',
    period: {
      current: { from: thisMonthStart, to: thisMonthEnd, label: latestMonth },
      previous: { from: prevMonthStart, to: prevMonthEnd, label: prevMonth },
      year_to_date: { from: yearStart, to: thisMonthEnd },
    },
    current_month: {
      income: current.income,
      expense: current.expense,
      net: current.net,
      transaction_count: txnCountThisMonth,
      top_categories: current.topCategories,
    },
    previous_month: {
      income: previous.income,
      expense: previous.expense,
      net: previous.net,
      transaction_count: txnCountPrevMonth,
      top_categories: previous.topCategories,
    },
    year_to_date: {
      income: yearAgg.income,
      expense: yearAgg.expense,
      net: yearAgg.net,
      top_categories: yearAgg.topCategories,
    },
    budgets: budgetSummaries,
    savings_goals: goalSummaries,
    alerts: alertSummaries,
    largest_expense_this_month: largestExpense ? {
      amount: Number(largestExpense.amount),
      date: largestExpense.txn_date,
      description: largestExpense.description,
      category_id: largestExpense.category_id,
      category: catById.get(largestExpense.category_id),
    } : null,
  };
}

