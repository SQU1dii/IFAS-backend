/**
 * AI Financial Assistant service — Enhanced Offline-First Version
 *
 * Architecture:
 *  1. Intent Classification (local, regex-based) → routes to deterministic handlers
 *  2. Rich Context Builder → fetches all data needed for factual answers
 *  3. Deterministic Handlers → compute exact answers from DB (no LLM needed)
 *  4. Template Engine → renders natural-language responses with real numbers
 *  5. LLM Fallback (optional) → only for open-ended "advice" questions
 *  6. Structured Response → JSON with answer, data, charts, follow-ups
 *
 * Security: ONLY aggregated figures ever leave the system. No raw transactions,
 * names, or descriptions are sent to any external provider.
 */
