'use strict';
/**
 * AI Financial Assistant service.
 *
 * Security principles enforced here:
 *  1. ONLY aggregated figures are sent to the AI provider — no names, no raw
 *     descriptions, no workspace member info.
 *  2. The prompt instructs the model to answer only from the supplied figures,
 *     give no investment or legal advice, and say "insufficient data" when needed.
 *  3. A limitations notice is appended to every AI response.
 *  4. The AI provider key is read from environment only — never logged.
 *  5. Rate limiting on the route keeps costs in check.
 *  6. If the AI provider is down, a clear "service unavailable" is returned;
 *     all other API endpoints keep working.
 */
const config         = require('../config');
const logger         = require('../config/logger');
const { getKnex }    = require('../config/database');
const alertRepo      = require('../repositories/alertRepository');
const budgetSvc      = require('./budget.service');
const { serviceUnavailable, badRequest } = require('../utils/errors');
const rateLimit      = require('express-rate-limit');

const db = () => getKnex();

const LIMITATIONS_NOTICE =
  '\n\n---\n*This response is generated by an AI assistant and is based solely on the ' +
  'aggregated financial figures supplied from your IFAS workspace. It does not constitute ' +
  'financial, investment, or legal advice. Always consult a qualified professional for ' +
  'important financial decisions.*';

// ── Context builder — aggregated figures only ─────────────────────────────────
async function buildContext(workspace, membership) {
  const wsId   = workspace.id;
  const wsType = workspace.workspace_type;
  const now    = new Date();
  const month  = now.toISOString().slice(0, 7);
  const from   = `${month}-01`;
  const to     = now.toISOString().slice(0, 10);

  const txns = await db()('transactions')
    .where({ workspace_id: wsId, status: 'POSTED' })
    .where('txn_date', '>=', from);

  let income = 0, expense = 0;
  const catMap = new Map();
  for (const r of txns) {
    if (r.txn_type === 'INCOME')  income  += Number(r.amount);
    if (r.txn_type === 'EXPENSE') { expense += Number(r.amount); catMap.set(r.category_id, (catMap.get(r.category_id) ?? 0) + Number(r.amount)); }
  }

  const openAlerts  = await alertRepo.countOpen(wsId);
  const budgets     = await budgetSvc.listBudgets(wsId);
  const budgetSummaries = await Promise.all(
    budgets.slice(0, 5).map((b) => budgetSvc.getBudgetStatus(wsId, b.id).catch(() => b))
  );

  // Only top-5 categories by spend (no descriptions, no names from source)
  const topCats = Array.from(catMap.entries()).sort(([,a],[,b]) => b-a).slice(0,5)
    .map(([category_id, total]) => ({ category_id, total_spent: total }));

  return {
    workspace_type: wsType,
    period: { from, to },
    income_this_month:  income,
    expense_this_month: expense,
    net_this_month:     income - expense,
    top_expense_categories: topCats,
    budgets: budgetSummaries.map((b) => ({
      id: b.id, amount_limit: b.amount_limit, spent: b.spent ?? 0, percent_used: b.percent_used ?? 0,
    })),
    open_alert_count: openAlerts,
  };
}

function buildSystemPrompt(context) {
  return `You are IFAS Financial Assistant — a helpful, concise financial analysis tool.

WORKSPACE CONTEXT (current month):
${JSON.stringify(context, null, 2)}

STRICT RULES — you MUST follow all of these:
1. Answer ONLY from the figures supplied above. Do not invent numbers.
2. If data is insufficient, say so clearly ("insufficient data").
3. Give NO investment advice, NO legal advice, NO specific product recommendations.
4. Do NOT reference specific bank names, people, or company names.
5. Keep answers concise and factual. Show calculations when helpful.
6. If asked about something outside personal finance analytics, politely decline.`;
}

// ── AI provider call ─────────────────────────────────────────────────────────
async function callAiProvider(messages) {
  if (config.ai.mode === 'mock') {
    return mockAiResponse(messages);
  }
  try {
    const axios = require('axios');
    const res = await axios.post(
      config.ai.url,
      { model: config.ai.model, messages },
      {
        timeout: config.ai.timeoutMs,
        headers: {
          Authorization: `Bearer ${config.ai.apiKey}`,
          'Content-Type': 'application/json',
        },
      },
    );
    return res.data.choices?.[0]?.message?.content ?? 'No response from AI provider.';
  } catch (err) {
    logger.warn('AI provider unavailable', { err: err.message });
    throw serviceUnavailable('The AI assistant is temporarily unavailable. Please try again later.');
  }
}

// ── Mock AI provider (used by default for local dev/tests) ────────────────────
function mockAiResponse(messages) {
  const userMsg = messages.filter((m) => m.role === 'user').slice(-1)[0]?.content ?? '';
  const lower   = userMsg.toLowerCase();

  if (lower.includes('expense') || lower.includes('spend')) {
    return 'Based on the current month\'s figures, your total expenses so far are recorded in your workspace context. Review the top expense categories for areas to reduce spending.';
  }
  if (lower.includes('income') || lower.includes('revenue')) {
    return 'Your income figures for the current month are available in the workspace context. Compare with your expense total to check your net position.';
  }
  if (lower.includes('budget')) {
    return 'Review your budget utilisation percentages in the workspace context. Any budget over 80% warrants attention before month-end.';
  }
  if (lower.includes('forecast') || lower.includes('predict')) {
    return 'Forecasts require at least 6 months of expense history. Use the /forecast endpoint to generate a projection for your workspace.';
  }
  return 'I can help with questions about your workspace financial figures — income, expenses, budgets, alerts, and trends. What would you like to know?';
}

// ── Conversation + message store ─────────────────────────────────────────────
async function sendMessage(workspace, userId, membership, userContent, conversationId) {
  if (!userContent || !userContent.trim()) throw badRequest('Message content is required.', null, 'EMPTY_MESSAGE');

  // Get or create conversation
  let convId = conversationId;
  if (!convId) {
    const [id] = await db()('conversations').insert({
      workspace_id: workspace.id,
      user_id:      userId,
      title:        userContent.slice(0, 60) || 'New conversation',
    });
    convId = id;
  } else {
    const existing = await db()('conversations').where({ id: convId, workspace_id: workspace.id, user_id: userId }).first();
    if (!existing) throw badRequest('Conversation not found.', null, 'CONV_NOT_FOUND');
  }

  // Load recent history (last 10 messages) for context
  const history = await db()('messages')
    .where({ conversation_id: convId })
    .orderBy('created_at', 'asc')
    .limit(10)
    .select('role', 'content');

  // Build context (aggregated figures only)
  const context = await buildContext(workspace, membership);
  const systemPrompt = buildSystemPrompt(context);

  const messages = [
    { role: 'system', content: systemPrompt },
    ...history.map((m) => ({ role: m.role, content: m.content })),
    { role: 'user', content: userContent },
  ];

  // Call AI provider
  const aiContent = await callAiProvider(messages);
  const finalContent = aiContent + LIMITATIONS_NOTICE;

  // Store user message + assistant response
  await db()('messages').insert({ conversation_id: convId, role: 'user',      content: userContent });
  await db()('messages').insert({ conversation_id: convId, role: 'assistant',  content: finalContent,
    context_snapshot: JSON.stringify(context) });

  // Update conversation timestamp
  await db()('conversations').where({ id: convId }).update({ updated_at: new Date().toISOString().slice(0, 19).replace('T', ' ') });

  return {
    conversation_id: convId,
    message: { role: 'assistant', content: finalContent },
    context_used: context,
  };
}

async function listConversations(workspaceId, userId) {
  return db()('conversations')
    .where({ workspace_id: workspaceId, user_id: userId })
    .orderBy('updated_at', 'desc')
    .select('id', 'title', 'created_at', 'updated_at');
}

async function getConversation(workspaceId, userId, convId) {
  const conv = await db()('conversations').where({ id: convId, workspace_id: workspaceId, user_id: userId }).first();
  if (!conv) throw require('../utils/errors').notFound('Conversation not found.', 'CONV_NOT_FOUND');
  const messages = await db()('messages').where({ conversation_id: convId }).orderBy('created_at', 'asc')
    .select('id', 'role', 'content', 'created_at');
  return { ...conv, messages };
}

module.exports = { sendMessage, listConversations, getConversation };
