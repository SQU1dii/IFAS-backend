// TEMPLATE ENGINE (deterministic natural-language responses)
// ============================================================================

function fmt(n) {
  return new Intl.NumberFormat('en-KE', { style: 'currency', currency: 'KES', maximumFractionDigits: 0 }).format(n);
}

function pct(n) {
  return `${Math.round(n)}%`;
}

const TEMPLATES = {
  MONTHLY_SUMMARY: (ctx) => {
    const { current_month } = ctx;
    const top = current_month.top_categories.slice(0, 3).map(c => `${c.category}: ${fmt(c.total)}`).join(', ');
    return `This month (${ctx.period.current.label}): you spent **${fmt(current_month.expense)}** across ${current_month.transaction_count} transactions. Top categories: ${top || 'none recorded'}. Income: ${fmt(current_month.income)}. Net: ${fmt(current_month.net)}.`;
  },

  INCOME_SUMMARY: (ctx) => {
    const { current_month } = ctx;
    return `This month (${ctx.period.current.label}): your income total is **${fmt(current_month.income)}**.`;
  },

  NET_POSITION: (ctx) => {
    const { current_month } = ctx;
    const word = current_month.net >= 0 ? 'surplus' : 'deficit';
    return `This month (${ctx.period.current.label}): you have a **${word} of ${fmt(Math.abs(current_month.net))}** (income ${fmt(current_month.income)} − expenses ${fmt(current_month.expense)}).`;
  },

  TOP_CATEGORIES: (ctx) => {
    const { current_month } = ctx;
    if (!current_month.top_categories.length) return 'No expense categories recorded this month yet.';
    const lines = current_month.top_categories.slice(0, 5).map((c, i) => `${i + 1}. ${c.category}: ${fmt(c.total)}`).join('\n');
    return `Top expense categories this month (${ctx.period.current.label}):\n${lines}`;
  },

  BUDGET_STATUS: (ctx) => {
    const { budgets } = ctx;
    if (!budgets.length) return 'No budgets set for the current month.';
    const over = budgets.filter(b => b.over);
    const near = budgets.filter(b => b.near && !b.over);
    const ok = budgets.filter(b => !b.near && !b.over);
    let msg = `**Budget status for ${ctx.period.current.label}:**\n`;
    if (over.length) msg += `\n🔴 **Over budget (${over.length}):**\n` + over.map(b => `• ${b.category}${b.department ? ` (${b.department})` : ''}: ${pct(b.percent)} used (${fmt(b.spent)} / ${fmt(b.limit)})`).join('\n');
    if (near.length) msg += `\n🟡 **Near limit (${near.length}):**\n` + near.map(b => `• ${b.category}${b.department ? ` (${b.department})` : ''}: ${pct(b.percent)} used (${fmt(b.spent)} / ${fmt(b.limit)})`).join('\n');
    if (ok.length) msg += `\n🟢 **On track (${ok.length}):**\n` + ok.map(b => `• ${b.category}${b.department ? ` (${b.department})` : ''}: ${pct(b.percent)} used`).join('\n');
    return msg;
  },

  SAVINGS_GOAL: (ctx) => {
    const { savings_goals } = ctx;
    if (!savings_goals.length) return 'No savings goals set for this workspace.';
    return savings_goals.map(g => {
      const monthsLeft = g.target_date ? Math.max(1, Math.ceil((new Date(g.target_date) - new Date()) / (1000 * 60 * 60 * 24 * 30))) : null;
      const monthlyNeeded = monthsLeft ? Math.ceil(g.remaining / monthsLeft) : null;
      let txt = `**${g.name}**: ${fmt(g.saved)} / ${fmt(g.target)} (${g.percent}% complete)`;
      if (g.remaining > 0) txt += ` — ${fmt(g.remaining)} to go`;
      if (monthlyNeeded) txt += ` (≈ ${fmt(monthlyNeeded)}/month for ${monthsLeft} months)`;
      if (g.target_date) txt += ` by ${g.target_date}`;
      return txt;
    }).join('\n\n');
  },

  ALERT_EXPLANATION: (ctx) => {
    const { alerts } = ctx;
    if (!alerts.length) return 'No open alerts in this workspace.';
    return alerts.map(a => {
      let icon = a.severity === 'HIGH' ? '🔴' : a.severity === 'MEDIUM' ? '🟡' : '🟢';
      return `${icon} **${a.type}** (${a.severity}): ${a.reason}\n*Created ${new Date(a.created_at).toLocaleDateString()}* — Review the transaction and verify the details.`;
    }).join('\n\n');
  },

  FORECAST: (ctx) => {
    return `I can generate forecasts using the /forecast endpoint, which requires at least 6 months of expense history. The forecast will include projected values with MAPE accuracy metrics. Would you like me to run a forecast for a specific category or overall expenses?`;
  },

  PERIOD_COMPARISON: (ctx) => {
    const { current_month, previous_month } = ctx;
    const expDiff = current_month.expense - previous_month.expense;
    const expPct = previous_month.expense > 0 ? ((expDiff / previous_month.expense) * 100).toFixed(1) : 'N/A';
    const incDiff = current_month.income - previous_month.income;
    const incPct = previous_month.income > 0 ? ((incDiff / previous_month.income) * 100).toFixed(1) : 'N/A';
    let msg = `**${ctx.period.previous.label} → ${ctx.period.current.label} comparison:**\n`;
    msg += `• Expenses: ${fmt(previous_month.expense)} → ${fmt(current_month.expense)} (${expDiff >= 0 ? '+' : ''}${fmt(expDiff)}, ${expDiff >= 0 ? '+' : ''}${expPct}%)\n`;
    msg += `• Income: ${fmt(previous_month.income)} → ${fmt(current_month.income)} (${incDiff >= 0 ? '+' : ''}${fmt(incDiff)}, ${incDiff >= 0 ? '+' : ''}${incPct}%)\n`;
    msg += `• Net: ${fmt(previous_month.net)} → ${fmt(current_month.net)}`;
    return msg;
  },

  CATEGORY_DETAIL: (ctx, question) => {
    const { current_month } = ctx;
    // Extract category from question (simple approach)
    const cats = current_month.top_categories;
    const mentioned = cats.find(c => question.toLowerCase().includes(c.category.toLowerCase()));
    if (mentioned) {
      return `**${mentioned.category}** this month (${ctx.period.current.label}): ${fmt(mentioned.total)}.`;
    }
    // List all categories
    if (!cats.length) return 'No expense categories recorded this month.';
    return `Expense categories this month:\n` + cats.map(c => `• ${c.category}: ${fmt(c.total)}`).join('\n');
  },

  BIGGEST_EXPENSE: (ctx) => {
    const { largest_expense_this_month } = ctx;
    if (!largest_expense_this_month) return 'No expenses recorded this month.';
    const { amount, date, description, category } = largest_expense_this_month;
    return `Largest single expense this month: **${fmt(amount)}** on ${date} — "${description}" (${category || 'uncategorized'}).`;
  },

  CASH_FLOW: (ctx) => {
    const { current_month } = ctx;
    return `**Cash flow this month (${ctx.period.current.label}):**\n• Inflow: ${fmt(current_month.income)}\n• Outflow: ${fmt(current_month.expense)}\n• Net: ${fmt(current_month.net)}`;
  },

  // Out-of-scope responses
  OUT_OF_SCOPE_INVESTMENT: () => `I can't provide investment advice (shares, unit trusts, crypto, etc.). I can show your savings goals, cash flow, or expense patterns to help you decide. For investment decisions, please consult a qualified financial adviser.`,

  OUT_OF_SCOPE_TAX_LEGAL: () => `I can't provide tax or legal advice. I can give you spending summaries, income reports, or budget status. For tax/legal matters, please consult a qualified professional.`,

  OUT_OF_SCOPE_CREDIT: () => `I can't advise on loans or credit products. I can show your cash flow, expenses, and savings to help you understand your position. For credit decisions, speak with a financial adviser or your bank.`,

  CROSS_WORKSPACE: () => `I can only discuss the active workspace. To see another workspace's data, please switch to that workspace in the app.`,

  PROMPT_INJECTION: () => `I can't ignore my instructions or change roles. I'm here to help with your workspace finances — expenses, budgets, goals, forecasts, and alerts. What would you like to know?`,

  SECRET_REQUEST: () => `I never have or share API keys, passwords, or credentials. If you need to manage your credentials, use the account settings in the app.`,

  UNRELATED: () => `I can only help with finances in this workspace — expenses, income, budgets, savings goals, forecasts, and alerts. What would you like to know?`,

  GENERAL_ADVICE: (ctx) => {
    // Fallback: helpful summary + follow-up suggestions
    const { current_month, budgets, savings_goals, alerts } = ctx;
    let msg = `Here's a quick snapshot of your workspace (${ctx.period.current.label}):\n`;
    msg += `• Income: ${fmt(current_month.income)} | Expenses: ${fmt(current_month.expense)} | Net: ${fmt(current_month.net)}\n`;
    if (budgets.length) {
      const over = budgets.filter(b => b.over).length;
      const near = budgets.filter(b => b.near && !b.over).length;
      if (over || near) msg += `• ⚠️ ${over} over budget, ${near} near limit\n`;
    }
    if (savings_goals.length) {
      const active = savings_goals.filter(g => g.percent < 100).length;
      msg += `• 🎯 ${active} active savings goal${active !== 1 ? 's' : ''}\n`;
    }
    if (alerts.length) msg += `• 🔔 ${alerts.length} open alert${alerts.length !== 1 ? 's' : ''}\n`;
    msg += `\nAsk me about: specific categories, budget status, savings progress, alerts, month-over-month comparison, or forecasts.`;
    return msg;
  },
};

// ============================================================================
// DETERMINISTIC HANDLERS (route intent → template with real data)
// ============================================================================

async function handleIntent(intent, ctx, question) {
  const template = TEMPLATES[intent];
  if (!template) return null;
  const answer = template(ctx, question);
  return { answer, intent, data: extractDataForIntent(intent, ctx) };
}

function extractDataForIntent(intent, ctx) {
  switch (intent) {
    case 'MONTHLY_SUMMARY':
    case 'INCOME_SUMMARY':
    case 'NET_POSITION':
    case 'CASH_FLOW':
      return { period: ctx.period.current, income: ctx.current_month.income, expense: ctx.current_month.expense, net: ctx.current_month.net };
    case 'TOP_CATEGORIES':
    case 'CATEGORY_DETAIL':
      return { period: ctx.period.current, categories: ctx.current_month.top_categories };
    case 'BUDGET_STATUS':
      return { period: ctx.period.current, budgets: ctx.budgets };
    case 'SAVINGS_GOAL':
      return { goals: ctx.savings_goals };
    case 'ALERT_EXPLANATION':
      return { alerts: ctx.alerts };
    case 'PERIOD_COMPARISON':
      return { current: ctx.current_month, previous: ctx.previous_month };
    case 'BIGGEST_EXPENSE':
      return { expense: ctx.largest_expense_this_month };
    case 'FORECAST':
      return { endpoint: '/analytics/forecast', requires: '6+ months history' };
    default:
      return {};
  }
}

