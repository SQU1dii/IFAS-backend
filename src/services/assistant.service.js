// CHART SUGGESTIONS (for frontend rendering)
// ============================================================================

function suggestCharts(intent, ctx) {
  switch (intent) {
    case 'MONTHLY_SUMMARY':
    case 'INCOME_SUMMARY':
    case 'NET_POSITION':
    case 'CASH_FLOW':
      return ['bar:monthly_income_expense', 'line:monthly_net'];
    case 'TOP_CATEGORIES':
    case 'CATEGORY_DETAIL':
      return ['pie:category_breakdown', 'bar:top_categories'];
    case 'BUDGET_STATUS':
      return ['gauge:budget_utilization', 'bar:budget_vs_actual'];
    case 'SAVINGS_GOAL':
      return ['progress:savings_goals', 'line:savings_trend'];
    case 'ALERT_EXPLANATION':
      return ['list:alerts'];
    case 'PERIOD_COMPARISON':
      return ['bar:month_comparison', 'line:expense_trend'];
    case 'BIGGEST_EXPENSE':
      return ['list:large_transactions'];
    case 'FORECAST':
      return ['line:forecast_with_confidence'];
    default:
      return ['bar:monthly_income_expense', 'pie:category_breakdown'];
  }
}

